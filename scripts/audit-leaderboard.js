#!/usr/bin/env node
/* eslint-disable no-console */
// Audit a track's leaderboard and quarantine rows the verifier network has
// already rejected (Invalid / InvalidDuplicate / InvalidManual).
//
// Usage:
//   node scripts/audit-leaderboard.js --track-id <sha256> [--track-id ...]
//        [--base https://...] [--version 0.5.2] [--amount 100] [--apply] [--json]
//
// The track id is the value the game sends as `trackId` (a SHA-256 of the
// track's contents); copy it from the browser's network tab while the
// leaderboard is open.
//
// --apply merges the offending row ids into worker/leaderboard-quarantine.mjs,
// which the Worker and the dev proxy use to drop those rows from every read.

const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");

const repoRoot = path.resolve(__dirname, "..");
const quarantinePath = path.join(repoRoot, "worker", "leaderboard-quarantine.mjs");
const DEFAULT_BASE = "https://polytrack-backend.htmlunblockedgames.workers.dev/";

function usage() {
  console.log(
    [
      "Usage: node scripts/audit-leaderboard.js --track-id <sha256> [options]",
      "",
      "  --track-id <id>   track id to audit (repeatable)",
      "  --base <url>      backend origin (default: the public backend)",
      "  --version <v>     game version sent with the request (default 0.5.2)",
      "  --amount <n>      page size (default 100)",
      "  --apply           merge rejected row ids into the quarantine module",
      "  --json            print the report as JSON",
    ].join("\n")
  );
}

function parseArgs(argv) {
  const options = {
    trackIds: [],
    base: DEFAULT_BASE,
    version: "0.5.2",
    amount: 100,
    apply: false,
    json: false,
  };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--help" || arg === "-h") {
      options.help = true;
    } else if (arg === "--track-id") {
      options.trackIds.push(argv[++i]);
    } else if (arg === "--base") {
      options.base = argv[++i];
    } else if (arg === "--version") {
      options.version = argv[++i];
    } else if (arg === "--amount") {
      options.amount = Number.parseInt(argv[++i], 10) || 100;
    } else if (arg === "--apply") {
      options.apply = true;
    } else if (arg === "--json") {
      options.json = true;
    } else {
      throw new Error(`Unknown option: ${arg}`);
    }
  }
  return options;
}

function formatFrames(frames) {
  const total = Math.abs(frames);
  const minutes = Math.floor(total / 60000);
  const seconds = Math.floor((total - minutes * 60000) / 1000);
  const millis = total - minutes * 60000 - seconds * 1000;
  return `${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}.${String(millis).padStart(3, "0")}`;
}

async function fetchEntries(base, trackId, version, amount) {
  const entries = [];
  let total = 0;
  let skip = 0;
  for (;;) {
    const params = new URLSearchParams({
      version,
      trackId,
      skip: String(skip),
      amount: String(amount),
      // Deliberately unfiltered: the point is to find the rows a verified-only
      // read no longer shows.
      onlyVerified: "false",
    });
    const response = await fetch(`${base.replace(/\/?$/, "/")}leaderboard?${params}`);
    if (!response.ok) throw new Error(`GET /leaderboard failed with HTTP ${response.status}`);
    const payload = await response.json();
    if (!Array.isArray(payload.entries)) throw new Error("GET /leaderboard returned no entries");
    total = Number.isSafeInteger(payload.total) ? payload.total : entries.length + payload.entries.length;
    entries.push(...payload.entries);
    skip += payload.entries.length;
    if (payload.entries.length === 0 || skip >= total || skip >= 1000) break;
  }
  return { total, entries };
}

function writeQuarantine(ids) {
  const existing = readQuarantine();
  const merged = new Set(existing);
  for (const id of ids) merged.add(id);
  const sorted = Array.from(merged).sort((a, b) => a - b);
  const body = [
    "/* Leaderboard rows this origin refuses to serve.",
    " *",
    " * Generated by:",
    " *   npm run audit:leaderboard -- --track-id <sha256> --apply",
    " *",
    " * Only rows the verifier network already rejected are listed here.",
    " */",
    `export default [${sorted.length ? "\n" + sorted.map((id) => `  ${id},`).join("\n") + "\n" : ""}];`,
    "",
  ].join("\n");
  fs.writeFileSync(quarantinePath, body);
  return { before: existing.length, after: sorted.length };
}

function readQuarantine() {
  if (!fs.existsSync(quarantinePath)) return [];
  const source = fs.readFileSync(quarantinePath, "utf8");
  const match = source.match(/export\s+default\s+\[([\s\S]*?)\]/);
  if (!match) return [];
  return (match[1].match(/\d+/g) || []).map(Number).filter((id) => Number.isSafeInteger(id) && id > 0);
}

(async () => {
  let options;
  try {
    options = parseArgs(process.argv.slice(2));
  } catch (err) {
    console.error(err.message);
    usage();
    process.exit(2);
  }
  if (options.help) {
    usage();
    return;
  }
  if (options.trackIds.length === 0) {
    console.error("At least one --track-id is required.");
    usage();
    process.exit(2);
  }

  const policy = await import(
    pathToFileURL(path.join(repoRoot, "worker", "leaderboard-policy.mjs")).href
  );

  const report = [];
  for (const trackId of options.trackIds) {
    const { total, entries } = await fetchEntries(
      options.base,
      trackId,
      options.version,
      options.amount
    );
    const classified = policy.classifyEntries(entries);
    report.push({
      trackId,
      total,
      fetched: entries.length,
      verified: classified.verified.length,
      pending: classified.pending.length,
      invalid: classified.invalid.length,
      unknown: classified.unknown.length,
      invalidIds: classified.invalid,
      pendingIds: classified.pending,
    });

    if (!options.json) {
      console.log(`\nTrack ${trackId} — ${total} rows, ${entries.length} inspected`);
      console.log(
        `  verified ${classified.verified.length}, pending ${classified.pending.length}, invalid ${classified.invalid.length}, unknown ${classified.unknown.length}`
      );
      for (const entry of entries) {
        const state = policy.describeVerifiedState(entry.verifiedState);
        if (state === "verified") continue;
        console.log(
          `  [${state}] id ${entry.id}  ${formatFrames(entry.frames)}  ${entry.name}`
        );
      }
    }
  }

  if (options.json) {
    console.log(JSON.stringify(report, null, 2));
  }

  if (options.apply) {
    const ids = report.flatMap((entry) => entry.invalidIds);
    if (ids.length === 0) {
      console.log("\nNothing to quarantine.");
      return;
    }
    const result = writeQuarantine(ids);
    console.log(
      `\nQuarantine now holds ${result.after} row ids (was ${result.before}). Redeploy to apply.`
    );
  } else if (report.some((entry) => entry.invalid.length > 0)) {
    console.log("\nRe-run with --apply to drop these rows from this origin's leaderboard.");
  }
})().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
